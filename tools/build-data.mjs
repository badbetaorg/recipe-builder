#!/usr/bin/env node
// Validate data/batches/*.json and bundle them into data/recipes.js, a plain
// script so the app also works when index.html is opened straight from disk.
// Usage: node tools/build-data.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { validateRecipe } from "./validate.mjs";

const dataDir = join(dirname(fileURLToPath(import.meta.url)), "..", "data");
const batchDir = join(dataDir, "batches");
const recipes = [];
const ids = new Set();
let failed = false;

for (const file of readdirSync(batchDir).filter((f) => f.endsWith(".json")).sort()) {
  for (const r of JSON.parse(readFileSync(join(batchDir, file), "utf8"))) {
    const errors = validateRecipe(r);
    if (ids.has(r.id)) errors.push(`${r.id}: duplicate id`);
    if (errors.length) {
      failed = true;
      errors.forEach((e) => console.error(`${file}: ${e}`));
      continue;
    }
    ids.add(r.id);
    recipes.push(r);
  }
}
if (failed) process.exit(1);

recipes.sort((a, b) => a.title.localeCompare(b.title));
writeFileSync(
  join(dataDir, "recipes.js"),
  "// Generated by tools/build-data.mjs from data/batches/*.json - edit those instead.\n" +
    "window.RECIPES = " + JSON.stringify(recipes, null, 1) + ";\n"
);
console.log(`Wrote ${recipes.length} recipes to data/recipes.js`);
